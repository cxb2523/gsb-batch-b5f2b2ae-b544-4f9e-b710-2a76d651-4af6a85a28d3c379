#!/usr/bin/env node
// Bundle src/index.ts + src/types.ts into examples/sim.js — a plain ES module
// a browser can load, with all TypeScript types stripped. No dependencies;
// uses Node's built-in type stripper (Node >= 22.18 / 24 strip by default).
//
//   node scripts/build-demo.mjs
//
// Then serve the repo root over HTTP and open examples/play.html:
//
//   npx serve .        (or: python -m http.server)
//   open http://localhost:3000/examples/play.html

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { stripTypeScriptTypes } from 'node:module';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');

function strip(relPath) {
  const source = readFileSync(join(root, relPath), 'utf8');
  return stripTypeScriptTypes(source, { mode: 'strip' });
}

let index = strip('src/index.ts');

// types.ts declares only types and has no runtime code, so nothing from it
// belongs in the bundle. Drop the local import a browser could not resolve.
index = index.replace(
  /import\s+(type\s+)?\{[\s\S]*?\}\s+from\s+['"]\.\/types\.ts['"];?/g,
  '',
);

const banner = `// Generated by scripts/build-demo.mjs — do not edit by hand.\n// Source: src/index.ts (types from src/types.ts are erased)\n\n`;
// Type-stripping leaves whitespace-only lines where annotations were; tidy them
// and collapse runs of blank lines so the generated file stays readable.
const bundle = `${banner}${index}`
  .replace(/^[ \t]+$/gm, '')
  .replace(/\n{3,}/g, '\n\n');

const outDir = join(root, 'examples');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'sim.js');
writeFileSync(outFile, bundle, 'utf8');
console.log(`wrote ${outFile} (${Buffer.byteLength(bundle)} bytes)`);

// Fail loudly if the bundle still contains TS-only syntax or a dangling import.
if (/^\s*(interface|type)\s+\w+/m.test(bundle)) {
  console.error('warning: bundle still looks like it contains type declarations');
  process.exitCode = 1;
}
if (/from\s+['"]\.\/types/.test(bundle)) {
  console.error('warning: bundle still imports ./types');
  process.exitCode = 1;
}
